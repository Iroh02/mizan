"""Mizan QA evaluation runner.

Runs the human-verified QA set against a running Mizan API and produces a
results table for review. Humans judge correctness; this script collects.

Usage:
    python evals/run_qa.py                          # against http://localhost:8000
    MIZAN_API_URL=https://mizan-jcdy.onrender.com python evals/run_qa.py

Input:  evals/qa_set.csv with columns:
        id,type,question,expected_answer,source_article
        (type: answerable | tricky | should_refuse)
Output: evals/qa_results.md — a markdown table with Mizan's answers alongside
        the expected ones, plus an automatic summary of refusal behaviour.
        A human fills the final verdict column; the script never self-grades
        correctness (that's the honest part).
"""
from __future__ import annotations

import csv
import os
import sys
import time
from pathlib import Path

import httpx

API = os.getenv("MIZAN_API_URL", "http://localhost:8000")
PAUSE_S = float(os.getenv("MIZAN_EVAL_PAUSE", "3"))  # be kind to free-tier rate limits


def main() -> None:
    src = Path(__file__).with_name("qa_set.csv")
    if not src.exists():
        sys.exit(f"Missing {src} — export the QA sheet as CSV with columns "
                 "id,type,question,expected_answer,source_article")
    rows = list(csv.DictReader(src.open(encoding="utf-8-sig")))
    if not rows:
        sys.exit("qa_set.csv is empty")
    print(f"Running {len(rows)} questions against {API}\n")

    results = []
    refusals_expected = refusals_correct = false_answers = 0
    with httpx.Client(timeout=120) as client:
        for i, row in enumerate(rows, 1):
            q = row["question"].strip()
            try:
                r = client.post(f"{API}/ask", json={"question": q})
                r.raise_for_status()
                data = r.json()
                answer, abstained = data["answer"], data["abstained"]
            except Exception as e:
                answer, abstained = f"ERROR: {e}", False
            should_refuse = row["type"].strip() == "should_refuse"
            if should_refuse:
                refusals_expected += 1
                if abstained:
                    refusals_correct += 1
                else:
                    false_answers += 1
            results.append({**row, "mizan_answer": answer.replace("\n", " ")[:600],
                            "abstained": abstained})
            print(f"[{i}/{len(rows)}] {'ABSTAINED' if abstained else 'answered '} — {q[:60]}")
            time.sleep(PAUSE_S)

    out = Path(__file__).with_name("qa_results.md")
    with out.open("w", encoding="utf-8") as f:
        f.write("# Mizan QA results\n\n")
        f.write(f"API: {API} · {len(rows)} questions · generated by evals/run_qa.py\n\n")
        f.write("## Automatic summary (refusal behaviour only)\n\n")
        f.write(f"- Deliberately unanswerable questions: **{refusals_expected}**\n")
        f.write(f"- Correctly refused: **{refusals_correct}**\n")
        f.write(f"- False answers (should have refused but answered): **{false_answers}**\n\n")
        f.write("## Full results — fill the Verdict column by hand\n\n")
        f.write("| # | Type | Question | Expected (human-verified) | Source | Mizan's answer | Abstained | VERDICT |\n")
        f.write("|---|------|----------|---------------------------|--------|----------------|-----------|--------|\n")
        for r in results:
            f.write(f"| {r['id']} | {r['type']} | {r['question']} | {r['expected_answer']} "
                    f"| {r['source_article']} | {r['mizan_answer']} | {r['abstained']} |  |\n")
    print(f"\nWrote {out} — open it, judge each answer, fill the VERDICT column.")
    print("Correctness is judged by humans against the cited law — never by this script.")


if __name__ == "__main__":
    main()
